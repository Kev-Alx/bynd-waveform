const { chromium }=require('/workspace/improvement/audio_browser_qa/node_modules/playwright');
const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const root='/workspace/improvement',qa=path.join(root,'execution_tradeoff/qa');
const checks=[],errors=[];
function record(name,detail={}){checks.push({name,status:'pass',...detail});console.log('PASS',name);}
async function main(){
  fs.mkdirSync(qa,{recursive:true});
  const browser=await chromium.launch({headless:true,args:['--no-sandbox','--mute-audio']});
  try{
    const context=await browser.newContext({viewport:{width:1440,height:1050},acceptDownloads:true});
    const page=await context.newPage();
    page.on('pageerror',e=>errors.push(String(e)));
    await page.goto('http://127.0.0.1:8888/',{waitUntil:'networkidle'});
    await page.getByRole('combobox',{name:'Run A',exact:true}).waitFor({timeout:30000});
    assert.equal(await page.locator('.lab-pane').count(),3);
    assert.equal(await page.locator('.lab-clip').count(),48);
    record('Default view: 3 run panels and 48 sentences');
    await page.screenshot({path:path.join(qa,'desktop-listening.png'),fullPage:true});
    await page.getByRole('combobox',{name:'Run C',exact:true}).selectOption('scaled-mel--mel_eot_200');
    assert.match(await page.locator('.lab-run-summary').nth(2).innerText(),/80\.18/);
    record('Changing a run updates its mean scores and recording');
    await page.getByRole('button',{name:'Clean / original / ensemble',exact:true}).click();
    await page.locator('audio').first().evaluate(a=>a.play());
    await page.waitForFunction(()=>document.querySelector('audio').currentTime>.3);
    const before=await page.locator('audio').first().evaluate(a=>a.currentTime);
    await page.locator('audio').nth(2).evaluate(a=>a.play());
    await page.waitForTimeout(250);
    const media=await page.locator('audio').evaluateAll(as=>as.map(a=>({paused:a.paused,time:a.currentTime,error:a.error?.message})));
    assert.equal(media[0].paused,true);assert.equal(media[2].paused,false);assert.ok(media[2].time>=before-.05);assert.ok(!media.some(m=>m.error));
    record('Original FLOAT WAV playback and linked A/B/C switching',{media});
    await page.getByRole('button',{name:'■ Stop audio',exact:true}).click();
    assert.ok((await page.locator('audio').evaluateAll(as=>as.map(a=>a.paused))).every(Boolean));
    await page.getByRole('slider',{name:'Seek run C',exact:true}).focus();
    await page.getByRole('slider',{name:'Seek run C',exact:true}).press('Home');
    await page.getByRole('slider',{name:'Seek run C',exact:true}).press('ArrowRight');
    assert.ok(await page.locator('audio').nth(2).evaluate(a=>a.currentTime>0));
    record('Stop-all and accessible seek control');
    await page.getByRole('combobox',{name:'Playback speed',exact:true}).selectOption('0.75');
    assert.ok((await page.locator('audio').evaluateAll(as=>as.map(a=>a.playbackRate))).every(r=>r===.75));
    record('Playback speed applies to all loaded panels');
    for(const n of [1,2,3]){await page.getByRole('button',{name:n+' '+(n===1?'panel':'panels'),exact:true}).click();assert.equal(await page.locator('.lab-pane').count(),n);}
    record('One, two or three comparison panels');
    const data=JSON.parse(fs.readFileSync(path.join(root,'audio_browser/src/data.json'),'utf8'));
    const small=new Set(data.queries.recordings.rows.filter(r=>r.runId==='r2--adversarial').map(r=>r.clipId));
    const missing=data.queries.clips.rows.find(r=>!small.has(r.id));
    await page.getByRole('combobox',{name:'Run C',exact:true}).selectOption('r2--adversarial');
    await page.locator('.lab-clip').filter({hasText:missing.id}).click();
    assert.equal(await page.getByText(/This sentence was not part/).count(),1);
    await page.getByRole('checkbox',{name:'Only sentences in every selected run'}).check();
    assert.equal(await page.locator('.lab-clip').count(),24);
    await page.getByRole('checkbox',{name:'Only sentences in every selected run'}).uncheck();
    await page.getByRole('searchbox',{name:'Search sentence, ID or speaker'}).fill('84-121123-0023');
    assert.equal(await page.locator('.lab-clip').count(),1);
    await page.getByRole('searchbox',{name:'Search sentence, ID or speaker'}).fill('');
    assert.equal(await page.locator('.lab-clip').count(),48);
    record('Absent-cohort message, shared-sentence filter and search reset');
    await page.getByText('All results',{exact:true}).click();
    await page.locator('.lab-table tbody tr').first().waitFor();
    assert.equal(await page.locator('.lab-table tbody tr').count(),data.queries.runs.rows.filter(r=>r.count===48).length);
    await page.getByLabel('Cohort',{exact:true}).selectOption('24');assert.equal(await page.locator('.lab-table tbody tr').count(),23);
    await page.getByLabel('Cohort',{exact:true}).selectOption('all');assert.equal(await page.locator('.lab-table tbody tr').count(),data.queries.runs.rows.length);
    await page.getByLabel('Study',{exact:true}).selectOption('BigVGAN mel-space pilot');assert.equal(await page.locator('.lab-table tbody tr').count(),5);
    await page.getByLabel('Quality',{exact:true}).selectOption('pass');assert.equal(await page.locator('.lab-table tbody tr').count(),2);
    await page.getByLabel('Quality',{exact:true}).selectOption('fail');assert.equal(await page.locator('.lab-table tbody tr').count(),3);
    await page.getByRole('button',{name:'Reset',exact:true}).click();assert.equal(await page.locator('.lab-table tbody tr').count(),data.queries.runs.rows.filter(r=>r.count===48).length);
    record('Cohort, study and quality filters reconcile and reset');
    await page.getByLabel('Sort',{exact:true}).selectOption('wer');
    assert.match(await page.locator('.lab-table tbody tr').first().innerText(),/101\.41/);
    const downloadPromise=page.waitForEvent('download');
    await page.getByRole('button',{name:'Export '+data.queries.runs.rows.filter(r=>r.count===48).length+' rows ↓',exact:true}).click();
    const download=await downloadPromise;await download.saveAs(path.join(qa,'exported-results.csv'));
    assert.equal(fs.readFileSync(path.join(qa,'exported-results.csv'),'utf8').split(/\r?\n/).length,data.queries.runs.rows.filter(r=>r.count===48).length+1);
    record('WER sorting and CSV export match visible rows');
    await page.screenshot({path:path.join(qa,'desktop-results.png'),fullPage:true});
    await page.getByText('Changes & next steps',{exact:true}).click();
    await page.getByText('What changed, in plain language',{exact:true}).waitFor();
    assert.match(await page.locator('.lab-explanation').innerText(),/Treat quality and cost together/);
    await page.screenshot({path:path.join(qa,'desktop-explanation.png'),fullPage:true});
    record('Plain-language explanation and future steps load');
    await page.getByText('Listen & compare',{exact:true}).click();
    await page.getByRole('button',{name:'Clean / original / ensemble',exact:true}).click();
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:path.join(qa,'mobile-listening.png'),fullPage:true});
    const geometry=await page.evaluate(()=>({viewport:innerWidth,width:document.documentElement.scrollWidth,panels:document.querySelectorAll('.lab-pane').length}));
    assert.ok(geometry.width<=geometry.viewport+1,JSON.stringify(geometry));
    record('Narrow layout: contained horizontal panel scrolling',{geometry});
    await page.setViewportSize({width:1440,height:1050});
    await page.getByRole('combobox',{name:'Run C',exact:true}).selectOption('tradeoff--anchor25');
    const expectedAnchor=data.queries.runs.rows.find(r=>r.id==='tradeoff--anchor25');
    assert.ok((await page.locator('.lab-run-summary').nth(2).innerText()).includes(expectedAnchor.wer.toFixed(2)));
    await page.locator('audio').nth(2).evaluate(a=>a.play());
    await page.waitForFunction(()=>document.querySelectorAll('audio')[2].currentTime>.3);
    await page.getByRole('button',{name:'■ Stop audio',exact:true}).click();
    record('New spectrum-repair recording plays with reconciled cohort metrics');
    await page.getByText('Runtime & scale',{exact:true}).click();
    await page.getByText('Quality and computational cost',{exact:true}).waitFor();
    assert.equal(await page.locator('.lab-runtime table tbody tr').count(),data.queries.runtime.rows.length);
    assert.equal(await page.locator('.lab-phase-track').count(),2);
    const research=data.queries.research.rows[0];
    assert.ok((await page.locator('.lab-runtime').innerText()).includes(research.speedReductionPercent.toFixed(1)+'%'));
    assert.ok((await page.locator('.lab-runtime').innerText()).includes(research.teacher10Hours.toFixed(2)));
    for (const filename of ['latency_per_recording.csv','runtime_catalogue.csv','results.json']){
      const response=await page.request.get('http://127.0.0.1:8888/'+filename);assert.equal(response.status(),200);assert.ok((await response.body()).length>100);
    }
    await page.screenshot({path:path.join(qa,'runtime-desktop.png'),fullPage:true});
    await page.setViewportSize({width:390,height:844});
    const runtimeGeometry=await page.evaluate(()=>({viewport:innerWidth,width:document.documentElement.scrollWidth}));
    assert.ok(runtimeGeometry.width<=runtimeGeometry.viewport+1,JSON.stringify(runtimeGeometry));
    await page.screenshot({path:path.join(qa,'runtime-mobile.png'),fullPage:true});
    record('Runtime rows, measured phase bars, forecast, downloadable receipts and narrow layout reconcile',{runtimeGeometry});
    assert.equal(errors.length,0,errors.join('\n'));
    record('No uncaught browser errors');
    fs.writeFileSync(path.join(root,'execution_tradeoff/browser_receipt.json'),JSON.stringify({status:'pass',checked_at_utc:new Date().toISOString(),checks,errors},null,2));
  }finally{await browser.close();}
}
main().catch(e=>{fs.writeFileSync(path.join(root,'execution_tradeoff/browser_receipt.json'),JSON.stringify({status:'failed',checked_at_utc:new Date().toISOString(),checks,errors,error:String(e),stack:e.stack},null,2));console.error(e);process.exitCode=1;});
